public class LearningData3 {
    public static void main(String[] args){
        char a=65;//char类型数据表示的是字符
        System.out.println(a);
        a='?';
        System.out.println(a);
        a='\n';
        System.out.println(a);
        a='\'';
        System.out.println(a);
        String b="hello world";//String类型数据表示的是字符串
        System.out.println(b);
    }
}
