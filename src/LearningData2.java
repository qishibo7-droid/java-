public class LearningData2 {
    public static void main(String[] args){
        float a=9.99F,b=0.01F;/*末尾要加F是因为输入小数的时候默认是double类，
        但double类型不能隐式转化成float类型，和之前的输入long类型整数的时候要在末尾加上L一样*/
        /*float 用 32 位存：1 符号位 + 8 指数位 + 23 尾数位
         决定“范围”的是指数位，决定“精度”的是尾数位，两者是两回事：
         float  8 位指数 → 范围约 ±3.4×10的38次方；23 位尾数 → 精度约 7 位有效数字
         double 11 位指数 → 范围约 ±1.8×10的308次方；52 位尾数 → 精度约 15~16 位有效数字
         注意区分：浮点数不是“小数点前后多少位”，而是“总共多少位有效数字” */
        float c;
        c=a+b;
        System.out.println(c);
        double d=1.33;//double 是 64 位：1 符号位 + 11 指数位 + 52 尾数位
        //浮点数字不能用于很精细的计算，因为它的计数方法天生有失真
        /*验证精度差别：
         1.0F / 3.0F  → 0.33333334           只保留 7 位就截断了
         1.0  / 3.0   → 0.3333333333333333   保留到 15 位以上
         */
        /*例如0.25可以通过：
        0.25 × 2 = 0.5   → 整数部分 = 0   ← 这一位是 0，剩下 0.5
        0.50 × 2 = 1.0   → 整数部分 = 1   ← 这一位是 1，剩下 0.0
        0.00       结束   （剩下是 0，不用再乘了）
        可以完全表示，但这个方法表示0.1的时候就会出现：
        0.1 × 2 = 0.2  → 0
        0.2 × 2 = 0.4  → 0
        0.4 × 2 = 0.8  → 0
        0.8 × 2 = 1.6  → 1   剩下 0.6
        0.6 × 2 = 1.2  → 1   剩下 0.2  ← 回到起点了
        这样会失真，导致只能表示近似值
         */
        /*long数据可以转化成float数据：
         float 的「范围」比 long 大（10的38次方 > 9.2×10的18次方），所以转换被允许；
         但 float 的「精度」不如 long（23 位尾数 vs 63 位数值），超出部分直接丢失。
         结论：范围够 ≠ 精度够
         */
        boolean Data= (0.3F==0.1F+0.2F);
        System.out.println(Data);
        //永远不要直接用==去对比两个浮点树，因为精度问题，在java中

    }
}
