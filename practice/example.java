public class example {
    public static void main(String[] args){
        int a=15;
        float b=27.32F;
        a=(int)b;
        System.out.println(Integer.toBinaryString(a));
        //强制转换去掉小数点后面的数字
    }
/*
 * ===== 27.32 转 float 编码（IEEE 754）=====
 * 布局：S(1) | E(8) | M(23)     值 = (-1)^S x 1.M x 2^E     bias = 127
 *
 * 1. 转二进制
 *    整数 27  -> 除2取余倒着读 -> 11011
 *    小数 0.32 -> 乘2取整正着读 -> 01010001111010111000...（20位一循环）
 *    27.32 = 11011.01010001111010111000...  ← 无限循环
 *    （0.32=8/25，分母含因子5，二进制必然循环；分母是2的幂才能精确）
 *
 * 2. 规格化：小数点左移4位
 *    1.10110101000111101011100... x 2^4
 *    E = 4   （速算：整数部分11011有5位，E = 5-1 = 4）
 *
 * 3. 尾数保留23位（多的截断）
 *    M = 10110101000111101011100
 *
 * 4. 阶码字段 = E + 127 = 4 + 127 = 131 = 10000011
 *
 * 5. 拼接：0 | 10000011 | 10110101000111101011100
 *         = 01000001110110101000111101011100
 *
 * 6. 转16进制：0100 0001 1101 1010 1000 1111 0101 1100
 *              4    1    D    A    8    F    5    C
 *         => 0x41DA8F5C
 *
 * 结论：27.32 不能精确表示，实际存的是 27.31999969482421875
 *      对比 5.25（101.01 有限）-> 精确，0x40A80000
 *      所以浮点数不能用 == 比较，要用 Math.abs(f - x) < 1e-6
 */
}
